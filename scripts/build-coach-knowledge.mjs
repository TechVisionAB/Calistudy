// Builds supabase/functions/coach/knowledge.ts: the guide + a description of the app,
// so the AI coach answers from the same source as the app. Re-run after changing
// docs/guide.md or the feature list in README.md:  node scripts/build-coach-knowledge.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const guide = readFileSync('docs/guide.md', 'utf8');
const readme = readFileSync('README.md', 'utf8');
const features = readme.slice(readme.indexOf('## Funktioner'), readme.indexOf('## Kom igång')).trim();

const glossarySrc = readFileSync('src/data/glossary.ts', 'utf8');
const glossary = [...glossarySrc.matchAll(/term: '([^']+)'.*?text: '((?:[^'\\]|\\.)*)'/g)].map(([, term, text]) => `- ${term}: ${text.replace(/\\'/g, "'")}`).join('\n');

const svSrc = readFileSync('src/data/sv.ts', 'utf8');
const levelBlock = svSrc.slice(svSrc.indexOf('export const LEVEL_SV'), svSrc.indexOf('};', svSrc.indexOf('export const LEVEL_SV')));
const levels = [...levelBlock.matchAll(/(\w+): '([^']+)'/g)].map(([, code, name]) => `${code} = ${name}`).join('; ');

const knowledge = `<app_description>
Appen Calistudy bygger på guiden nedan. Så fungerar appen (flikar: Idag, Program, Nivåer, Logg, Guide):

${features}

Svenska namn på nivåerna i appen: ${levels}
</app_description>

<glossary>
${glossary}
</glossary>

<guide>
${guide}
</guide>`;

writeFileSync(
  'supabase/functions/coach/knowledge.ts',
  `// GENERATED by scripts/build-coach-knowledge.mjs — do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`,
);
console.log(`knowledge.ts written (${Math.round(knowledge.length / 1000)} kB)`);
